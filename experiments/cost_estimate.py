"""Cost estimate for the 90-call run from the real rendered prompts + models.json prices. No network.
  python -m experiments.cost_estimate [--write docs/cost-estimate.md]
Expected = measured prompt chars/4 and the gold-answer JSON length/3.3 as output; Worst case = the budget module's own
pessimistic estimate (chars/3 x1.25 + full max_output cap), which is what the enforced budget reserves per call."""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

from . import inputs as inp
from . import models_file
from .config import TECHNIQUES_PROVISIONAL
from .prompts import render

ROOT = Path(__file__).resolve().parent.parent


def estimate(models_json: str | Path = ROOT / "models.json") -> dict:
    mf = models_file.load(models_json)
    built = inp.build(write=False)
    prompts = [
        render(t, r["text"]) for t in TECHNIQUES_PROVISIONAL for r in built["test"]
    ]
    exp_out_chars = sum(
        len(json.dumps({"events": [{**e["expected"], "evidence_quote": "x" * 60}]}))
        for e in built["expected"]
    ) / len(built["expected"])
    bud = mf.make_budget(ROOT / "outputs" / "estimate_ledger.jsonl")
    cfg, rows, tot_exp, tot_worst = mf.budget_cfg, [], 0.0, 0.0
    for s in mf.specs:
        p = mf.prices[s.model_id]
        in_chars = sum(len(a) + len(b) for a, b in prompts)
        in_exp = in_chars / 4  # typical English
        out_exp = len(prompts) * exp_out_chars / 3.3
        exp_usd = in_exp * p.usd_in_per_m / 1e6 + out_exp * p.usd_out_per_m / 1e6
        worst = sum(bud.estimate_usd(s.model_id, a, b) for a, b in prompts)
        in_worst = sum(
            math.ceil((len(a) + len(b)) / cfg.chars_per_token * cfg.input_margin) + 32
            for a, b in prompts
        )
        rows.append(
            {
                "provider": s.provider,
                "model_id": s.model_id,
                "calls": len(prompts),
                "in_tokens_expected": round(in_exp),
                "out_tokens_expected": round(out_exp),
                "in_tokens_budgeted": in_worst,
                "out_tokens_cap_total": len(prompts) * s.max_output_tokens,
                "expected_usd": exp_usd,
                "worst_case_usd": worst,
                "expected_eur": exp_usd / cfg.usd_per_eur,
                "worst_case_eur": worst / cfg.usd_per_eur,
            }
        )
        tot_exp += exp_usd
        tot_worst += worst
    return {
        "rows": rows,
        "total_expected_usd": tot_exp,
        "total_worst_usd": tot_worst,
        "total_expected_eur": tot_exp / cfg.usd_per_eur,
        "total_worst_eur": tot_worst / cfg.usd_per_eur,
        "cap_eur": cfg.cap_eur,
        "cap_usd_conservative": cfg.cap_usd,
        "usd_per_eur": cfg.usd_per_eur,
        "calls_total": len(prompts) * len(mf.specs),
    }


def to_markdown(e: dict) -> str:
    L = [
        "# Cost estimate: 90 calls (3 models x 3 techniques x 10 records)",
        "",
        f"Generated by `python -m experiments.cost_estimate` from the real rendered prompts and `models.json` (prices from official pages, retrieved 2026-11-19; FX {e['usd_per_eur']} USD/EUR, ECB 2026-11-18). No call has been made.",
        "",
        "| model | calls | input tok (expected / budgeted) | output tok (expected / capped) | expected | worst case |",
        "|---|---|---|---|---|---|",
    ]
    for r in e["rows"]:
        L.append(
            f"| {r['model_id']} | {r['calls']} | {r['in_tokens_expected']} / {r['in_tokens_budgeted']} | {r['out_tokens_expected']} / {r['out_tokens_cap_total']} | ${r['expected_usd']:.4f} (EUR {r['expected_eur']:.4f}) | ${r['worst_case_usd']:.4f} (EUR {r['worst_case_eur']:.4f}) |"
        )
    L += [
        "",
        f"**Total expected:** ${e['total_expected_usd']:.4f} (EUR {e['total_expected_eur']:.4f}). **Total worst case:** ${e['total_worst_usd']:.4f} (EUR {e['total_worst_eur']:.4f}) against the enforced cap of EUR {e['cap_eur']} (= ${e['cap_usd_conservative']:.2f} after a 5% FX safety margin).",
        "",
        "Assumptions: expected tokens use chars/4 for input and chars/3.3 for output (not the providers' tokenisers, so +/-30%); worst case reserves chars/3 x 1.25 input plus the full per-call output cap, and charges Mistral at its higher listed rate for both directions (input/output order unverified). Gemini thinking tokens (level MINIMAL) are billed as output and are NOT in the expected figure, but the worst case already reserves the full per-call output cap (1024 tokens) for them. The budget is enforced per attempt (see `experiments/budget.py`), including retries.",
    ]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------- free-tier plan ----
def free_plan(models_json: str | Path = ROOT / "models.free.json") -> dict:
    """Token-aware, rate-limited plan for a FREE configuration: reserved tokens per call vs the free quotas, and the minimum
    wall-clock time the pacing guard will take. Uses the real rendered prompts; reserved = input estimate + full output cap."""
    from .ratelimit import FreeTierGuard

    mf = models_file.load(models_json)
    if mf.mode != "free":
        raise ValueError("free_plan needs a mode=free models file")
    built = inp.build(write=False)
    prompts = [
        render(t, r["text"]) for t in TECHNIQUES_PROVISIONAL for r in built["test"]
    ]
    g = FreeTierGuard(
        mf.limits,
        {s.model_id: s.max_output_tokens for s in mf.specs},
        ROOT / "outputs" / "estimate_free_ledger.jsonl",
        mf.budget_cfg,
    )
    rows, total_s = [], 0.0
    for s in mf.specs:
        lim = mf.limits[s.model_id]
        per_call = [g.estimate_tokens(s.model_id, a, b) for a, b in prompts]
        reserved_total, n = sum(per_call), len(per_call)
        by_tpm = reserved_total / lim.tpm * 60
        by_rpm = n / lim.rpm * 60
        secs = max(by_tpm, by_rpm)
        total_s += secs
        p = mf.prices[s.model_id]
        in_exp = sum(len(a) + len(b) for a, b in prompts) / 4
        shadow = (in_exp * p.usd_in_per_m + n * 110 * p.usd_out_per_m) / 1e6
        rows.append(
            {
                "model_id": s.model_id,
                "provider": s.provider,
                "calls": n,
                "max_reserved_per_call": max(per_call),
                "reserved_total": reserved_total,
                "rpd_use": n / lim.rpd,
                "tpd_use": reserved_total / lim.tpd,
                "min_minutes": secs / 60,
                "limiting": "tokens/min" if by_tpm >= by_rpm else "requests/min",
                "limits": {
                    "rpm": lim.rpm,
                    "rpd": lim.rpd,
                    "tpm": lim.tpm,
                    "tpd": lim.tpd,
                    "verified": lim.verified,
                },
                "list_price_shadow_usd": shadow,
            }
        )
    return {
        "rows": rows,
        "total_minutes": total_s / 60,
        "calls_total": len(prompts) * len(mf.specs),
    }


def free_markdown(e: dict) -> str:
    L = [
        "# Token-aware, rate-limited plan: free-tier configuration (`models.free.json`)",
        "",
        "Generated by `python -m experiments.cost_estimate --free` from the real rendered prompts. Nothing is billed; no call has been made. Reserved tokens = input estimate (chars/3 x 1.25) + the full per-call output cap, charged against tokens-per-minute because it is not documented whether output caps count.",
        "",
        "| model | calls | max reserved/call | reserved total | requests/day used | tokens/day used | limits (rpm / rpd / tpm / tpd) | limits verified | min. time (limited by) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in e["rows"]:
        lm = r["limits"]
        L.append(
            f"| {r['model_id']} | {r['calls']} | {r['max_reserved_per_call']} | {r['reserved_total']} | {r['rpd_use']:.1%} | {r['tpd_use']:.1%} | {lm['rpm']} / {lm['rpd']} / {lm['tpm']} / {lm['tpd']} | {'yes (source in config)' if lm['verified'] else 'NO: assumption'} | {r['min_minutes']:.1f} min ({r['limiting']}) |"
        )
    L += [
        "",
        f"**Total:** {e['calls_total']} calls, at least {e['total_minutes']:.0f} minutes of paced wall-clock time (models run one after another). Every model stays within its daily quotas (highest use of requests/day: {max(e['rows'], key=lambda r: r['rpd_use'])['model_id']}, {max(r['rpd_use'] for r in e['rows']):.0%}). The limits column shows the limits the guard enforces, which can be lower than a provider's ceiling (`pace_rpm` in `models.free.json`).",
        "",
        "Execution rules: the guard sleeps until the next call fits the rolling 60-second request and token windows; a daily quota that would be exceeded halts the run safely (checkpointed, resumable); 429/503 responses honour the provider's retry guidance (`Retry-After` header or Google's `retryDelay`); failed attempts are counted against the quotas; Groq responses are checked against the Free-plan header maxima and the run aborts if a paid plan is detected.",
        "",
        "Shadow reference only (nothing is charged): at list prices these 90 calls would cost about "
        + ", ".join(
            f"${r['list_price_shadow_usd']:.4f} ({r['model_id']})" for r in e["rows"]
        )
        + ".",
    ]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    if "--free" in sys.argv:
        est = free_plan(
            sys.argv[sys.argv.index("--models") + 1]
            if "--models" in sys.argv
            else ROOT / "models.free.json"
        )
        md = free_markdown(est)
    else:
        est = estimate()
        md = to_markdown(est)
    if "--write" in sys.argv:
        Path(sys.argv[sys.argv.index("--write") + 1]).write_text(md)
    print(md)
